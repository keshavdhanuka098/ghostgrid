"""Contract for pluggable models. Implement fit, predict and save in a model adapter."""
from typing import Any, Protocol
class ModelAdapter(Protocol):
    def fit(self, features: list[dict[str, Any]], targets: list[Any], validation: tuple[list[dict[str, Any]], list[Any]] | None = None) -> None: ...
    def predict(self, features: list[dict[str, Any]]) -> list[Any]: ...
    def save(self, path: str) -> None: ...
